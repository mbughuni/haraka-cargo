/**
 * Generates lib/geo/trade-map-geometry.ts: pre-projected SVG paths for the
 * Africa–Asia trade-route map.
 *
 *   node scripts/generate-trade-map.mjs
 *
 * Source data: Natural Earth 1:110m (public domain) via the world-atlas
 * package. Boundaries are Natural Earth's de facto representation at small
 * scale. They are illustrative and not authoritative.
 *
 * Only the static land and highlighted-country shapes are baked in. Route
 * waypoints and locations live in lib/trade-routes.ts and are projected at
 * render time with the same parameters, so adding a route does not require
 * running this script again.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { geoNaturalEarth1, geoPath } from "d3-geo"
import { feature, merge } from "topojson-client"

const require = createRequire(import.meta.url)
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")

const WIDTH = 1000
const ROTATE_LONGITUDE = -62
// Longitude and latitude bounds of the visible window.
const BOUNDS = { west: -20, east: 128, south: -36, north: 44 }

// ISO 3166-1 numeric codes. Keep in sync with CountryId in lib/trade-routes.ts.
const COUNTRIES = {
  TZ: "834",
  IN: "356",
  CN: "156",
  AE: "784",
  KE: "404",
  UG: "800",
  RW: "646",
  BI: "108",
  ZM: "894",
  MW: "454",
  MZ: "508",
  CD: "180",
}

const topology = JSON.parse(
  readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8")
)

function boundsPolygon({ west, east, south, north }) {
  const ring = []
  for (let lon = west; lon <= east; lon += 1) ring.push([lon, south])
  for (let lat = south; lat <= north; lat += 1) ring.push([east, lat])
  for (let lon = east; lon >= west; lon -= 1) ring.push([lon, north])
  for (let lat = north; lat >= south; lat -= 1) ring.push([west, lat])
  return { type: "Polygon", coordinates: [ring.reverse()] }
}

const window = boundsPolygon(BOUNDS)
const probe = geoNaturalEarth1()
  .rotate([ROTATE_LONGITUDE, 0])
  .fitWidth(WIDTH, window)
const [[, y0], [, y1]] = geoPath(probe).bounds(window)
const HEIGHT = Math.round(y1 - y0)

const projection = geoNaturalEarth1()
  .rotate([ROTATE_LONGITUDE, 0])
  .fitSize([WIDTH, HEIGHT], window)
  .clipExtent([
    [0, 0],
    [WIDTH, HEIGHT],
  ])
  .precision(0.4)

const path = geoPath(projection).digits(1)

const geometries = topology.objects.countries.geometries
const land = merge(topology, geometries)
const landPath = path(land)

const countryPaths = {}
for (const [code, id] of Object.entries(COUNTRIES)) {
  const geometry = geometries.find((item) => item.id === id)
  if (!geometry) throw new Error(`Country ${code} (${id}) not found`)
  countryPaths[code] = path(feature(topology, geometry))
}

// Verify that the lightweight runtime projection in lib/geo/project.ts
// matches d3 for a few known points.
const scale = projection.scale()
const [tx, ty] = projection.translate()
function runtimeProject([lon, lat]) {
  const lambda = ((lon + ROTATE_LONGITUDE) * Math.PI) / 180
  const phi = (lat * Math.PI) / 180
  const phi2 = phi * phi
  const phi4 = phi2 * phi2
  const x =
    lambda *
    (0.8707 -
      0.131979 * phi2 +
      phi4 * (-0.013791 + phi4 * (0.003971 * phi2 - 0.001529 * phi4)))
  const y =
    phi *
    (1.007226 +
      phi2 * (0.015085 + phi4 * (-0.044475 + 0.028874 * phi2 - 0.005916 * phi4)))
  return [tx + scale * x, ty - scale * y]
}
for (const point of [
  [72.95, 18.95],
  [39.28, -6.82],
  [113.26, 23.13],
]) {
  const [ax, ay] = projection(point)
  const [bx, by] = runtimeProject(point)
  if (Math.abs(ax - bx) > 0.01 || Math.abs(ay - by) > 0.01) {
    throw new Error(`Runtime projection mismatch at ${point}`)
  }
}

const output = `// GENERATED by scripts/generate-trade-map.mjs. Do not edit by hand.
// Source: Natural Earth 1:110m (public domain) via world-atlas@2.0.2.
// Boundaries are small-scale, de facto and illustrative only.

export const tradeMapProjection = {
  width: ${WIDTH},
  height: ${HEIGHT},
  scale: ${scale.toFixed(4)},
  translate: [${tx.toFixed(4)}, ${ty.toFixed(4)}] as const,
  rotateLongitude: ${ROTATE_LONGITUDE},
}

export const landPath =
  ${JSON.stringify(landPath)}

export const countryPaths = ${JSON.stringify(countryPaths, null, 2)} as const
`

const target = resolve(root, "lib/geo/trade-map-geometry.ts")
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, output)
console.log(
  `Wrote ${target} (${WIDTH}×${HEIGHT}, ${(output.length / 1024).toFixed(1)} KB)`
)
