/**
 * TRADE NETWORK MODEL
 *
 * Describes where Haraka Cargo sources from and delivers to. This is a
 * statement of the service's scope, not shipment tracking. Lane status must
 * reflect reality:
 *   active       Haraka accepts sourcing requests on this lane today.
 *   planned      Announced as a future lane. No requests accepted yet.
 *   unavailable  Shown for context only. Not served.
 *
 * Waypoints are approximate sea-lane bends used to draw a readable curve.
 * They are not vessel routes or positions.
 */
import type { LonLat } from "@/lib/geo/project"

export type LaneStatus = "active" | "planned" | "unavailable"

/** ISO 3166-1 alpha-2. Shapes are generated by scripts/generate-trade-map.mjs. */
export type CountryId =
  | "TZ"
  | "IN"
  | "CN"
  | "AE"
  | "KE"
  | "UG"
  | "RW"
  | "BI"
  | "ZM"
  | "MW"
  | "MZ"
  | "CD"

export type TradeLocation = {
  id: string
  /** Main label, e.g. the country. */
  name: string
  /** Secondary label, e.g. a port or hub. Omit when not yet decided. */
  detail?: string
  country: CountryId
  coordinates: LonLat
  role: "origin" | "destination"
  status: LaneStatus
  /** Where the label sits relative to the marker. */
  labelSide: "left" | "right" | "top"
  /** For top labels: which edge of the label lines up with the marker. */
  labelAlign?: "center" | "end"
  /** Hide the label on narrow screens to avoid collisions. */
  secondary?: boolean
}

export type TradeLane = {
  id: string
  from: TradeLocation["id"]
  to: TradeLocation["id"]
  status: LaneStatus
  modes: ("sea" | "air")[]
  waypoints: LonLat[]
}

export type MarketRegion = {
  country: CountryId
  name: string
  status: LaneStatus
}

