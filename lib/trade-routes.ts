export const laneStatusLabel: Record<LaneStatus, string> = {
  active: "Active",
  planned: "Planned",
  unavailable: "Not yet served",
}

export function getLocation(id: string) {
  return tradeLocations.find((location) => location.id === id)
}

/** Plain-language summary for screen readers and captions. */
export function describeTradeNetwork() {
  const lanes = tradeLanes.map((lane) => {
    const from = getLocation(lane.from)
    const to = getLocation(lane.to)
    return `${from?.name} to ${to?.name}: ${laneStatusLabel[lane.status].toLowerCase()}`
  })
  return lanes
}
